def build_features(df_in):
    df = df_in.copy()

    codes_judiciaires = ["60","65","70","71","72","73","74","75"]
    df["dirigeant_role_str"] = df["dirigeant_role"].fillna("").astype(str).str.strip()
    df["dirigeant_est_judiciaire"]  = df["dirigeant_role_str"].isin(codes_judiciaires).astype(int)
    df["dirigeant_est_liquidateur"] = (df["dirigeant_role_str"] == "73").astype(int)
    df["dirigeant_est_mandataire"]  = (df["dirigeant_role_str"] == "65").astype(int)

    def parse_annee(ddn):
        try:
            s = str(ddn).strip()
            if len(s) >= 4 and s[:4].isdigit():
                return int(s[:4])
        except:
            pass
        return np.nan

    df["dirigeant_age"] = df["dirigeant_ddn"].apply(parse_annee)
    df["dirigeant_age"] = 2026 - df["dirigeant_age"]
    df["dirigeant_age"] = df["dirigeant_age"].where(df["dirigeant_age"].between(18, 100), np.nan)
    df["dirigeant_age_risque"] = np.where(
        df["dirigeant_age"].isna(), 0,
        ((df["dirigeant_age"] < 25) | (df["dirigeant_age"] > 70)).astype(int)
    )

    capital = pd.to_numeric(df["identite.montantCapital"], errors="coerce")
    df["capital_symbolique"]  = (capital == 1).astype(int)
    df["capital_tres_faible"] = capital.between(0, 1000, inclusive="both").astype(int)
    df["capital_absent"]      = capital.isna().astype(int)

    nb_rep = pd.to_numeric(df["nombreRepresentantsActifs"], errors="coerce").fillna(0)
    df["pas_representant_actif"] = (nb_rep == 0).astype(int)

    formes_obligatoires = ["5499","5710","5720","5599","5531","5560","5498","5308"]
    fj      = df["identite.formeJuridique"].fillna("").astype(str).str.strip()
    age_num = pd.to_numeric(df["age_ans"], errors="coerce").fillna(0)
    nb_ann  = pd.to_numeric(df.get("nb_annonces_bodacc",  pd.Series(0, index=df.index)), errors="coerce").fillna(0)
    flag_depot = pd.to_numeric(df.get("flag_depot_comptes", pd.Series(0, index=df.index)), errors="coerce").fillna(0)
    df["depot_non_respecte"] = (
        fj.isin(formes_obligatoires) & (flag_depot == 0) & (age_num > 2)
    ).astype(int)

    df["frequence_bodacc"] = np.where(age_num > 0, (nb_ann / age_num).round(4), 0.0)

    nb_etab_ouv = pd.to_numeric(df.get("nombreEtablissementsOuverts", pd.Series(0, index=df.index)), errors="coerce").fillna(0)
    nb_obs      = pd.to_numeric(df.get("nb_observations",             pd.Series(0, index=df.index)), errors="coerce").fillna(0)
    taux        = pd.to_numeric(df.get("taux_cessation_sectoriel",    pd.Series(0, index=df.index)), errors="coerce").fillna(0)

    df["frequence_observations"] = np.where(age_num > 0, (nb_obs / age_num).round(4), 0.0)
    df["jeune_secteur_risque"]   = ((age_num < 3) & (taux > taux.mean())).astype(int)
    df["ancienne_inactive"]      = ((age_num > 20) & (nb_ann == 0) & (nb_etab_ouv == 0)).astype(int)

    est_micro = df.get("est_micro", pd.Series(0, index=df.index)).fillna(0).astype(int)
    df["micro_sans_capital"] = ((est_micro == 1) & (capital.isna() | (capital == 0))).astype(int)

    return df

