def prepare_X(df_in, le_dict, fit=False):
    X = df_in[FEATURES_NUM + FEATURES_CAT].copy()
    for col in FEATURES_CAT:
        X[col] = X[col].fillna("Inconnu").astype(str)
        if fit:
            # Forcer "Inconnu" dans les classes pour gérer les valeurs inconnues au test
            all_vals = list(X[col].unique()) + ["Inconnu"]
            le = LabelEncoder()
            le.fit(all_vals)
            X[col] = le.transform(X[col])
            le_dict[col] = le
        else:
            X[col] = le_dict[col].transform(
                X[col].map(lambda x: x if x in le_dict[col].classes_ else "Inconnu")
            )
    for col in FEATURES_NUM:
        X[col] = pd.to_numeric(X[col], errors="coerce")
    return X


