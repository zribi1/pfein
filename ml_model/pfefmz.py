def score_physique(row):
    score = 60.0
    score -= row.get("flag_procedure_collective",    0) * 40
    score -= row.get("has_alerte_juridique",          0) * 30
    score -= row.get("dirigeant_est_judiciaire",      0) * 25
    score -= row.get("dirigeant_est_liquidateur",     0) * 15
    score -= row.get("depot_non_respecte",            0) * 10
    score -= row.get("pas_representant_actif",        0) * 10   # valide ici (pas de ML)
    score -= min(row.get("nb_annonces_bodacc",        0) * 2, 10)
    score -= min(row.get("nb_observations_critiques", 0) * 5, 20)
    score -= row.get("capital_absent",                0) * 5    # valide ici (pas de ML)
    score -= row.get("capital_tres_faible",           0) * 3
    taux = row.get("taux_cessation_sectoriel", 0.068) or 0.068
    score -= min(max(0, (taux/0.068 - 1) * 5), 10)
    return round(max(0, min(100, score)), 2)

def niveau_risque(score):
    if score >= 65: return "Faible"
    if score >= 45: return "Modéré"
    if score >= 25: return "Élevé"
