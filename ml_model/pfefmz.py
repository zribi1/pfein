import pandas as pd
import numpy as np
import warnings
warnings.filterwarnings("ignore")

from sklearn.model_selection import train_test_split
from sklearn.metrics import roc_auc_score, f1_score, recall_score
from sklearn.ensemble import RandomForestClassifier

from xgboost import XGBClassifier
from lightgbm import LGBMClassifier, early_stopping
from catboost import CatBoostClassifier


# ============================================================
# DATA
# ============================================================
df = pd.read_parquet('/content/drive/MyDrive/pfefmz/enterprises_clean.parquet')

y = df["est_active"]

X = df.select_dtypes(include=np.number).drop(columns=["est_active"], errors="ignore")
X = X.fillna(0)


# ============================================================
# SPLIT
# ============================================================
X_temp, X_test, y_temp, y_test = train_test_split(
    X, y,
    test_size=0.20,
    stratify=y,
    random_state=42
)

X_train, X_val, y_train, y_val = train_test_split(
    X_temp, y_temp,
    test_size=0.20,
    stratify=y_temp,
    random_state=42
)


# ============================================================
# MODELES
# ============================================================
models = {

    "XGBoost": XGBClassifier(
        n_estimators=1000,
        max_depth=6,
        learning_rate=0.05,
        subsample=0.8,
        colsample_bytree=0.8,
        eval_metric="logloss",
        early_stopping_rounds=30,
        random_state=42
    ),

    "LightGBM": LGBMClassifier(
        n_estimators=1000,
        max_depth=6,
        learning_rate=0.05,
        random_state=42
    ),

    "CatBoost": CatBoostClassifier(
        iterations=1000,
        depth=6,
        learning_rate=0.05,
        early_stopping_rounds=30,
        verbose=0,
        random_seed=42
    ),

    "RandomForest": RandomForestClassifier(
        n_estimators=300,
        max_depth=12,
        min_samples_leaf=5,
        class_weight="balanced",
        random_state=42,
        n_jobs=-1
    )
}


# ============================================================
# TRAIN
# ============================================================
fitted = {}

for name, model in models.items():

    print("="*60)
    print(name)

    if name == "XGBoost":

        model.fit(
            X_train,
            y_train,
            eval_set=[(X_val, y_val)],
            verbose=False
        )

    elif name == "LightGBM":

        model.fit(
            X_train,
            y_train,
            eval_set=[(X_val, y_val)],
            eval_metric="auc",
            callbacks=[early_stopping(30, verbose=False)]
        )

    elif name == "CatBoost":

        model.fit(
            X_train,
            y_train,
            eval_set=(X_val, y_val),
            verbose=False
        )

    else:

        model.fit(X_train, y_train)

    fitted[name] = model


# ============================================================
# RESULTATS
# ============================================================
rows = []

for name, model in fitted.items():

    p_train = model.predict_proba(X_train)[:,1]
    p_test = model.predict_proba(X_test)[:,1]
    pred = model.predict(X_test)

    auc_train = roc_auc_score(y_train, p_train)
    auc_test = roc_auc_score(y_test, p_test)

    f1 = f1_score(y_test, pred)
    rec = recall_score(y_test, pred)

    gap = auc_train - auc_test

    rows.append([
        name,
        round(auc_train,4),
        round(auc_test,4),
        round(gap,4),
        round(f1,4),
        round(rec,4)
    ])


df_resultats = pd.DataFrame(rows, columns=[
    "Modele",
    "AUC_Train",
    "AUC_Test",
    "Gap",
    "F1",
    "Recall"
])

print(df_resultats)

